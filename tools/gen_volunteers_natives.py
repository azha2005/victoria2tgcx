def generate():
    pe=PE(EXE);assert hashlib.sha256(pe.data).hexdigest()==SHA
    reloc=pe.relocations();rows=[];gate=[]
    for rva,n in [(r,32) for r in FUNCTIONS]+[(r,n*4) for r,n in TABLES]:
        positions=[p-rva for p in reloc if rva<=p<rva+n]
        for p in positions:
            if p+4>n:n=p
        positions=[p for p in positions if p+4<=n]
        data=pe.data[pe.offset(rva):pe.offset(rva)+n]
        rows.append(f'    Signature {{ rva:0x{rva:X}, bytes:&{list(data)!r}, relocations:&{positions!r} }},')
        gate.append((rva,data.hex().upper(),f'Volunteers native adapter RVA 0x{rva:X}'))
    target=ROOT/'rust/volunteers/src/native_signatures.rs'
    target.write_text('// Generated by tools/gen_volunteers_natives.py from the reference executable.\n'
        '// RVA + loaded base only; every absolute operand is relocated when compared.\n'
        'pub struct Signature { pub rva:u32, pub bytes:&\'static [u8], pub relocations:&\'static [usize] }\n'
        'pub static SIGNATURES:&[Signature]=&[\n'+'\n'.join(rows)+'\n];\n',encoding='ascii')
    print(f'Wrote {len(rows)} scoped signatures to {target}')
    (ROOT/'tools/tgcx_volunteers_signatures.py').write_text(
        '# Generated from reference SHA-256 '+SHA+'; see gen_volunteers_natives.py.\n'
        'SIGNATURES = '+repr(gate)+'\n',encoding='ascii')

if __name__=='__main__':generate()
