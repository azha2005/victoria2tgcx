"""Generate the separate province-rename plugin's relocation-aware guard table."""
import argparse
import hashlib
from pathlib import Path
import check_exe
from tgcx_pe import PE
from tgcx_rename_signatures import SIGNATURES

OUTPUT = Path(__file__).resolve().parent.parent / 'dll/province_rename/tgcx_rename_signatures.h'


def generate(exe):
    image = PE(exe)
    if hashlib.sha256(image.data).hexdigest() != check_exe.SHA256:
        raise ValueError('unsupported executable')
    lines = ['// Generated by tools/gen_rename_signatures.py.', '#pragma once',
             f'constexpr char tgcx_rename_sha[]="{check_exe.SHA256}";',
             f'constexpr uint32_t tgcx_rename_image_size=0x{image.image_size:X};',
             'struct tgcx_RenameSignature {uint32_t rva; unsigned char bytes[32]; unsigned size; int reloc[8]; unsigned count; const char* name;};',
             'constexpr tgcx_RenameSignature tgcx_rename_signatures[]={']
    for rva, expected, name in SIGNATURES:
        data = bytes.fromhex(expected)
        if image.data[image.offset(rva):image.offset(rva)+len(data)] != data:
            raise ValueError(f'signature mismatch at {rva:X}')
        relocs = [p-rva for p in image.relocations() if rva-3 <= p < rva+len(data)]
        if any(p < 0 or p+4 > len(data) for p in relocs):
            raise ValueError('partial relocation')
        lines.append('    {0x%X,{%s},%d,{%s},%d,"%s"},' % (
            rva, ','.join('0x%02X'%b for b in data), len(data), ','.join(map(str,relocs)) or '0', len(relocs), name))
    return '\n'.join(lines+['};',''])


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--exe', default=check_exe.DEFAULT_EXE)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    content = generate(args.exe)
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != content:
            raise SystemExit('province rename: stale signature header')
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(content, encoding='utf-8', newline='\n')
    print(f'province rename: {len(SIGNATURES)} signatures OK')
